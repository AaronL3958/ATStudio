import assert from 'node:assert/strict';
import {build} from 'esbuild';
await build({entryPoints:['app/video-presentation.ts'],outfile:'.sites-runtime/video-presentation-test.mjs',bundle:true,platform:'node',format:'esm'});
const {canVideoFullscreen,canVideoPip,enterVideoFullscreen,toggleVideoPip}=await import('../.sites-runtime/video-presentation-test.mjs');
assert.equal(canVideoFullscreen({},{}),false);
assert.equal(canVideoPip({},{}),false);
await assert.rejects(()=>enterVideoFullscreen({readyState:0},{}),/Wait for the video/);
await assert.rejects(()=>enterVideoFullscreen({readyState:4},{}),/does not allow fullscreen/);
let called=false;
const safari={readyState:4,webkitSupportsFullscreen:true,webkitEnterFullscreen(){called=true}};
const promise=enterVideoFullscreen(safari,{});
assert(called,'Safari fullscreen must be called synchronously within the tap');await promise;
let options;const doc={fullscreenEnabled:true,fullscreenElement:null};
const standard={readyState:4,async requestFullscreen(value){options=value;doc.fullscreenElement=this}};
await enterVideoFullscreen(standard,doc);assert.equal(options.navigationUI,'hide');
await assert.rejects(()=>enterVideoFullscreen({...standard,requestFullscreen:async()=>{}},{fullscreenEnabled:true}),/does not allow fullscreen/);
await assert.rejects(()=>enterVideoFullscreen({...standard,requestFullscreen:async()=>{throw Error('Blocked')}},doc),/Blocked/);
assert.equal(canVideoFullscreen(standard,{fullscreenEnabled:false}),false);
const pip={readyState:4,webkitPresentationMode:'inline',webkitSupportsPresentationMode:m=>m==='picture-in-picture',webkitSetPresentationMode(m){this.webkitPresentationMode=m}};
assert(canVideoPip(pip,{}));await toggleVideoPip(pip,{});assert.equal(pip.webkitPresentationMode,'picture-in-picture');await toggleVideoPip(pip,{});assert.equal(pip.webkitPresentationMode,'inline');
const pipDoc={pictureInPictureEnabled:true,pictureInPictureElement:null,async exitPictureInPicture(){this.pictureInPictureElement=null}};
const pipStandard={readyState:4,async requestPictureInPicture(){pipDoc.pictureInPictureElement=this}};
assert(canVideoPip(pipStandard,pipDoc));await toggleVideoPip(pipStandard,pipDoc);assert.equal(pipDoc.pictureInPictureElement,pipStandard);await toggleVideoPip(pipStandard,pipDoc);assert.equal(pipDoc.pictureInPictureElement,null);
assert.equal(canVideoPip({...pipStandard,disablePictureInPicture:true},pipDoc),false);
await assert.rejects(()=>toggleVideoPip({readyState:4},{}),/unavailable/);
console.log('PASS: native Safari activation, standard fullscreen navigation UI, rejected/unsupported APIs, and Safari/standard PiP enter/exit.');
